import { chart } from "../../../../../src/index.js";
import { frame, paint, patternFixture } from "./fixture.js";

// Explicit concrete primitive authoring. Geometry and visual inputs have one owner.
export function createPatternPrimitive(style = "diagonal") {
  const fixture = patternFixture(style);
  return chart().createGraphics({ id: "canvas", type: "canvas" })
    .editGraphics({ target: "canvas", property: "width", value: frame.width })
    .editGraphics({ target: "canvas", property: "height", value: frame.height })
    .editGraphics({ target: "canvas", property: "background", value: "white" })
    .createGraphics({ id: "plot-main", type: "collection", parent: "canvas" })
    .createGraphics({ id: "underlay", type: "path", parent: "plot-main" })
    .editGraphics({ target: "underlay", property: "commands", value: fixture.underlay })
    .editGraphics({ target: "underlay", property: "fillRule", value: "nonzero" })
    .editGraphics({ target: "underlay", property: "fill", value: paint.underlay })
    .createGraphics({ id: "background", type: "path", parent: "plot-main" })
    .editGraphics({ target: "background", property: "commands", value: fixture.background })
    .editGraphics({ target: "background", property: "fillRule", value: "nonzero" })
    .editGraphics({ target: "background", property: "fill", value: paint.background })
    .createGraphics({ id: "pattern-0", type: "path", parent: "plot-main" })
    .editGraphics({ target: "pattern-0", property: "commands", value: fixture.bars[0].commands })
    .editGraphics({ target: "pattern-0", property: "fillRule", value: "nonzero" })
    .editGraphics({ target: "pattern-0", property: "fill", value: fixture.bars[0].options.foreground })
    .editGraphics({ target: "pattern-0", property: "opacity", value: fixture.bars[0].opacity })
    .editGraphics({ target: "pattern-0", property: "clip", value: fixture.bars[0].clip })
    .createGraphics({ id: "pattern-1", type: "path", parent: "plot-main" })
    .editGraphics({ target: "pattern-1", property: "commands", value: fixture.bars[1].commands })
    .editGraphics({ target: "pattern-1", property: "fillRule", value: "nonzero" })
    .editGraphics({ target: "pattern-1", property: "fill", value: fixture.bars[1].options.foreground })
    .editGraphics({ target: "pattern-1", property: "opacity", value: fixture.bars[1].opacity })
    .editGraphics({ target: "pattern-1", property: "clip", value: fixture.bars[1].clip })
    .createGraphics({ id: "pattern-2", type: "path", parent: "plot-main" })
    .editGraphics({ target: "pattern-2", property: "commands", value: fixture.bars[2].commands })
    .editGraphics({ target: "pattern-2", property: "fillRule", value: "nonzero" })
    .editGraphics({ target: "pattern-2", property: "fill", value: fixture.bars[2].options.foreground })
    .editGraphics({ target: "pattern-2", property: "opacity", value: fixture.bars[2].opacity })
    .editGraphics({ target: "pattern-2", property: "clip", value: fixture.bars[2].clip })
    .createGraphics({ id: "pattern-3", type: "path", parent: "plot-main" })
    .editGraphics({ target: "pattern-3", property: "commands", value: fixture.bars[3].commands })
    .editGraphics({ target: "pattern-3", property: "fillRule", value: "nonzero" })
    .editGraphics({ target: "pattern-3", property: "fill", value: fixture.bars[3].options.foreground })
    .editGraphics({ target: "pattern-3", property: "opacity", value: fixture.bars[3].opacity })
    .editGraphics({ target: "pattern-3", property: "clip", value: fixture.bars[3].clip })
    .createGraphics({ id: "pattern-4", type: "path", parent: "plot-main" })
    .editGraphics({ target: "pattern-4", property: "commands", value: fixture.bars[4].commands })
    .editGraphics({ target: "pattern-4", property: "fillRule", value: "nonzero" })
    .editGraphics({ target: "pattern-4", property: "fill", value: fixture.bars[4].options.foreground })
    .editGraphics({ target: "pattern-4", property: "opacity", value: fixture.bars[4].opacity })
    .editGraphics({ target: "pattern-4", property: "clip", value: fixture.bars[4].clip })
    .createGraphics({ id: "pattern-5", type: "path", parent: "plot-main" })
    .editGraphics({ target: "pattern-5", property: "commands", value: fixture.bars[5].commands })
    .editGraphics({ target: "pattern-5", property: "fillRule", value: "nonzero" })
    .editGraphics({ target: "pattern-5", property: "fill", value: fixture.bars[5].options.foreground })
    .editGraphics({ target: "pattern-5", property: "opacity", value: fixture.bars[5].opacity })
    .editGraphics({ target: "pattern-5", property: "clip", value: fixture.bars[5].clip })
    .createGraphics({ id: "pattern-6", type: "path", parent: "plot-main" })
    .editGraphics({ target: "pattern-6", property: "commands", value: fixture.bars[6].commands })
    .editGraphics({ target: "pattern-6", property: "fillRule", value: "nonzero" })
    .editGraphics({ target: "pattern-6", property: "fill", value: fixture.bars[6].options.foreground })
    .editGraphics({ target: "pattern-6", property: "opacity", value: fixture.bars[6].opacity })
    .editGraphics({ target: "pattern-6", property: "clip", value: fixture.bars[6].clip })
    .createGraphics({ id: "pattern-7", type: "path", parent: "plot-main" })
    .editGraphics({ target: "pattern-7", property: "commands", value: fixture.bars[7].commands })
    .editGraphics({ target: "pattern-7", property: "fillRule", value: "nonzero" })
    .editGraphics({ target: "pattern-7", property: "fill", value: fixture.bars[7].options.foreground })
    .editGraphics({ target: "pattern-7", property: "opacity", value: fixture.bars[7].opacity })
    .editGraphics({ target: "pattern-7", property: "clip", value: fixture.bars[7].clip })
    .createGraphics({ id: "labels", type: "text", parent: "plot-main", length: 12 })
    .editGraphics({ target: "labels", property: "x", value: fixture.labels.x })
    .editGraphics({ target: "labels", property: "y", value: fixture.labels.y })
    .editGraphics({ target: "labels", property: "text", value: fixture.labels.text })
    .editGraphics({ target: "labels", property: "fill", value: paint.text })
    .editGraphics({ target: "labels", property: "fontSize", value: 12 })
    .editGraphics({ target: "labels", property: "fontFamily", value: "Arial" })
    .editGraphics({ target: "labels", property: "fontWeight", value: "normal" })
    .editGraphics({ target: "labels", property: "textAlign", value: "left" })
    .editGraphics({ target: "labels", property: "textBaseline", value: "alphabetic" })
    .editGraphics({ target: "labels", property: "rotation", value: 0 });
}
