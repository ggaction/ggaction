import { chart } from "../../../src/index.js";
import { axisOwnerScene } from "../../oracles/guide-owner-scenes.js";

// Explicit primitive chain driven only by the independent authored scene.
export function createAxisOwnersPrimitive() {
  const scene = axisOwnerScene();
  return chart()
    .createGraphics({"id":"canvas","type":"canvas"})
    .editGraphics({target:"canvas",property:"width",value:scene["canvas"].properties["width"]})
    .editGraphics({target:"canvas",property:"height",value:scene["canvas"].properties["height"]})
    .editGraphics({target:"canvas",property:"background",value:scene["canvas"].properties["background"]})
    .createGraphics({"id":"plot-main","type":"collection","parent":"canvas"})
    .createGraphics({"id":"horizontalGridLines","type":"line","parent":"plot-main","length":3})
    .editGraphics({target:"horizontalGridLines",property:"items",value:scene["horizontalGridLines"].items})
    .createGraphics({"id":"scatterPlot","type":"circle","parent":"plot-main","length":3})
    .editGraphics({target:"scatterPlot",property:"items",value:scene["scatterPlot"].items})
    .createGraphics({"id":"xAxisLine","type":"line","parent":"plot-main"})
    .editGraphics({target:"xAxisLine",property:"x1",value:scene["xAxisLine"].properties["x1"]})
    .editGraphics({target:"xAxisLine",property:"y1",value:scene["xAxisLine"].properties["y1"]})
    .editGraphics({target:"xAxisLine",property:"x2",value:scene["xAxisLine"].properties["x2"]})
    .editGraphics({target:"xAxisLine",property:"y2",value:scene["xAxisLine"].properties["y2"]})
    .editGraphics({target:"xAxisLine",property:"stroke",value:scene["xAxisLine"].properties["stroke"]})
    .editGraphics({target:"xAxisLine",property:"strokeWidth",value:scene["xAxisLine"].properties["strokeWidth"]})
    .createGraphics({"id":"xAxisTitle","type":"text","parent":"plot-main"})
    .editGraphics({target:"xAxisTitle",property:"x",value:scene["xAxisTitle"].properties["x"]})
    .editGraphics({target:"xAxisTitle",property:"y",value:scene["xAxisTitle"].properties["y"]})
    .editGraphics({target:"xAxisTitle",property:"text",value:scene["xAxisTitle"].properties["text"]})
    .editGraphics({target:"xAxisTitle",property:"fill",value:scene["xAxisTitle"].properties["fill"]})
    .editGraphics({target:"xAxisTitle",property:"fontSize",value:scene["xAxisTitle"].properties["fontSize"]})
    .editGraphics({target:"xAxisTitle",property:"fontFamily",value:scene["xAxisTitle"].properties["fontFamily"]})
    .editGraphics({target:"xAxisTitle",property:"fontWeight",value:scene["xAxisTitle"].properties["fontWeight"]})
    .editGraphics({target:"xAxisTitle",property:"textAlign",value:scene["xAxisTitle"].properties["textAlign"]})
    .editGraphics({target:"xAxisTitle",property:"textBaseline",value:scene["xAxisTitle"].properties["textBaseline"]})
    .editGraphics({target:"xAxisTitle",property:"rotation",value:scene["xAxisTitle"].properties["rotation"]})
    .createGraphics({"id":"axis_quantity__Line","type":"line","parent":"plot-main"})
    .editGraphics({target:"axis_quantity__Line",property:"x1",value:scene["axis_quantity__Line"].properties["x1"]})
    .editGraphics({target:"axis_quantity__Line",property:"y1",value:scene["axis_quantity__Line"].properties["y1"]})
    .editGraphics({target:"axis_quantity__Line",property:"x2",value:scene["axis_quantity__Line"].properties["x2"]})
    .editGraphics({target:"axis_quantity__Line",property:"y2",value:scene["axis_quantity__Line"].properties["y2"]})
    .editGraphics({target:"axis_quantity__Line",property:"stroke",value:scene["axis_quantity__Line"].properties["stroke"]})
    .editGraphics({target:"axis_quantity__Line",property:"strokeWidth",value:scene["axis_quantity__Line"].properties["strokeWidth"]})
    .createGraphics({"id":"axis_quantity__Ticks","type":"line","parent":"plot-main","length":3})
    .editGraphics({target:"axis_quantity__Ticks",property:"items",value:scene["axis_quantity__Ticks"].items})
    .createGraphics({"id":"axis_quantity__Labels","type":"text","parent":"plot-main","length":3})
    .editGraphics({target:"axis_quantity__Labels",property:"items",value:scene["axis_quantity__Labels"].items})
    .createGraphics({"id":"axis_quantity__Title","type":"text","parent":"plot-main"})
    .editGraphics({target:"axis_quantity__Title",property:"x",value:scene["axis_quantity__Title"].properties["x"]})
    .editGraphics({target:"axis_quantity__Title",property:"y",value:scene["axis_quantity__Title"].properties["y"]})
    .editGraphics({target:"axis_quantity__Title",property:"text",value:scene["axis_quantity__Title"].properties["text"]})
    .editGraphics({target:"axis_quantity__Title",property:"fill",value:scene["axis_quantity__Title"].properties["fill"]})
    .editGraphics({target:"axis_quantity__Title",property:"fontSize",value:scene["axis_quantity__Title"].properties["fontSize"]})
    .editGraphics({target:"axis_quantity__Title",property:"fontFamily",value:scene["axis_quantity__Title"].properties["fontFamily"]})
    .editGraphics({target:"axis_quantity__Title",property:"fontWeight",value:scene["axis_quantity__Title"].properties["fontWeight"]})
    .editGraphics({target:"axis_quantity__Title",property:"textAlign",value:scene["axis_quantity__Title"].properties["textAlign"]})
    .editGraphics({target:"axis_quantity__Title",property:"textBaseline",value:scene["axis_quantity__Title"].properties["textBaseline"]})
    .editGraphics({target:"axis_quantity__Title",property:"rotation",value:scene["axis_quantity__Title"].properties["rotation"]});
}
