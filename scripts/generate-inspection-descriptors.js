import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const cardsFile = path.join(root, "knowledge/action-cards.json");
const catalogFile = path.join(root, "agent_docs/contract/ACTION_INDEX.json");
const outputFile = path.join(root, "src/inspectionDescriptors.js");

function optionKind(name, type) {
  if (["target", "source", "data", "coordinate", "scale", "id"].includes(name)) return "resource";
  if (["field", "x", "y", "groupBy", "category", "value"].includes(name)) return "field";
  if (/domain|range|extent/i.test(name)) return "range";
  if (/readonly .*\[\]|\[.*\]/.test(type)) return "array";
  if (/\bboolean\b|\btrue\b|\bfalse\b/.test(type) && !/\bnumber\b|\bstring\b/.test(type)) return "boolean";
  if (/\bnumber\b/.test(type) && !/\bstring\b/.test(type)) return "number";
  if (/\bstring\b/.test(type) && !/[{[]/.test(type)) return "string";
  if (/^"[^"]+"(?: \| "[^"]+")*(?: \| undefined)?$/.test(type)) return "enum";
  return "object";
}

function choices(type) {
  if (/[{[]/.test(type)) return null;
  const values = [...type.matchAll(/"([^"]+)"|\b(true|false|null)\b/g)]
    .map(match => match[1] ?? JSON.parse(match[2]));
  return values.length > 0 ? [...new Set(values)] : null;
}

export async function buildInspectionDescriptors() {
  const cards = JSON.parse(await readFile(cardsFile, "utf8")).cards;
  const records = cards.map(card => [
    card.name,
    card.options.map(option => [
      option.name,
      option.required,
      optionKind(option.name, option.type),
      choices(option.type),
      card.units.find(unit => unit.path === option.name)?.unit ?? null
    ]),
    card.resources.idOptions,
    card.resources.prerequisites,
    card.supports.entryPoints
  ]);
  const catalog = JSON.parse(await readFile(catalogFile, "utf8"));
  const names = new Set(records.map(record => record[0]));
  for (const name of [...new Set(Object.values(catalog.internal).flat())].sort()) {
    if (!names.has(name)) records.push([name, [], [], ["internal action context"], ["internal"]]);
  }
  return [
    "// Generated by scripts/generate-inspection-descriptors.js.",
    "// Compact runtime facts derived from the public action-card contract.",
    `export const BUILTIN_ACTION_DESCRIPTOR_RECORDS = ${JSON.stringify(records)};`,
    ""
  ].join("\n");
}

export async function generateInspectionDescriptors({ check = false } = {}) {
  const expected = await buildInspectionDescriptors();
  if (check) {
    const actual = await readFile(outputFile, "utf8").catch(() => undefined);
    if (actual !== expected) throw new Error("Inspection descriptors are stale.");
    return;
  }
  await writeFile(outputFile, expected);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  await generateInspectionDescriptors({ check: process.argv.includes("--check") });
}
