"""Rebuild the small licensed examples; requires fonttools==4.60.1."""
import hashlib
import json
from pathlib import Path
from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

root = Path(__file__).parent
upstream = root.parents[2] / ".artifacts/font-public/upstream"
fixtures = [
    ("NotoSansKR-Regular.otf", "69975a0ac8472717870aefeab0a4d52739308d90856b9955313b2ad5e0148d68",
     "korean.otf", "ggaction Korean Fixture", "한글 글꼴과 긴 이름 ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789 .,!?:-é\u0301"),
    ("NotoEmoji.ttf", "de6c18832938afc99caf132b39d6a30a19bac7f2e812e28db2535b4608d27551",
     "emoji.ttf", "ggaction Emoji Fixture", "👩‍🔬 🙂 🇩🇰"),
]
manifest = []
for original, digest, output, family, text in fixtures:
    data = (upstream / original).read_bytes()
    assert hashlib.sha256(data).hexdigest() == digest
    font = TTFont(upstream / original, recalcTimestamp=False)
    if "fvar" in font:
        font = instantiateVariableFont(font, {"wght": 400}, inplace=True)
    options = subset.Options()
    options.name_IDs = [0, 1, 2, 3, 4, 5, 6, 13, 14]
    options.name_legacy = True
    options.name_languages = [0x409]
    subsetter = subset.Subsetter(options=options)
    subsetter.populate(text=text)
    subsetter.subset(font)
    for record in font["name"].names:
        value = {1: family, 3: family + " 1", 4: family, 6: family.replace(" ", "")}.get(record.nameID)
        if value is not None:
            record.string = value.encode(record.getEncoding())
    if "CFF " in font:
        top = font["CFF "].cff.topDictIndex[0]
        top.FamilyName = family
        top.FullName = family
        font["CFF "].cff.fontNames = [family.replace(" ", "")]
    font["head"].created = font["head"].modified = 2082844800
    font.save(root / output)
    payload = (root / output).read_bytes()
    cmap = font.getBestCmap()
    widths = {character: font["hmtx"].metrics[cmap[ord(character)]][0]
              for character in sorted(set(text)) if ord(character) in cmap}
    manifest.append({"file": output, "family": family, "mimeType": "font/otf" if output.endswith("otf") else "font/ttf",
        "byteLength": len(payload), "sha256": hashlib.sha256(payload).hexdigest(), "unitsPerEm": font["head"].unitsPerEm,
        "advances": widths, "sourceFile": original, "sourceSha256": digest})
(root / "manifest.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n")
(root / "manifest.js").write_text("// Generated by subset.py from the fixed font binaries.\nexport const fonts = " + json.dumps(manifest, ensure_ascii=False, indent=2) + ";\n")
